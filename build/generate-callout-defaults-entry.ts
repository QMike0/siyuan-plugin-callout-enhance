import * as fs from "fs";
import * as path from "path";
import { buildCalloutStaticStylesheet } from "../src/utils/callout_dynamic_styles";

const header = "/* Generated by build/generate-callout-defaults.cjs — do not edit */\n";
const css = buildCalloutStaticStylesheet();
const outFile = path.join(__dirname, "../src/callout_defaults.css");

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, header + css + (css.endsWith("\n") ? "" : "\n"), "utf8");
